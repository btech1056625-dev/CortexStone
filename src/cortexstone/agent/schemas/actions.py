"""
src/cortexstone/agent/schemas/actions.py

Typed action and planning schemas generated by Nemotron 3 Super 120B.
Co-owned by Archis Samanta (ML/DL) and Himanshu (Agentic AI).

INVARIANT:
- Model proposes actions; backend policy evaluates risk and authorization.
- Model MUST NOT supply authorization, risk tiers, or bypassed approval flags.
- Schema rejects extra fields (`extra='forbid'`).
"""
from __future__ import annotations

import uuid
from datetime import datetime, timezone
from typing import Any
from pydantic import BaseModel, ConfigDict, Field


class ProposedAction(BaseModel):
    """
    A single bounded tool action proposed by the agent.
    Never executes directly; must pass server-side policy and approval.
    """
    model_config = ConfigDict(extra="forbid")

    action_id: uuid.UUID = Field(
        default_factory=uuid.uuid4,
        description="Unique identifier for this action proposal"
    )
    tool_name: str = Field(
        description="Registered tool identifier (e.g., 'github.create_draft_pr', 'notes.search')"
    )
    target_ref: str = Field(
        description="Target resource (e.g., 'owner/repo', 'calendar_id', 'note_slug')"
    )
    arguments: dict[str, Any] = Field(
        default_factory=dict,
        description="Explicit parameters required by the tool"
    )
    purpose: str = Field(
        description="Clear, truthful explanation of why this action is required"
    )
    idempotency_key: str | None = Field(
        default=None,
        description="Unique key ensuring safe replay without duplicate side-effects"
    )
    requested_at: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc),
        description="Timestamp of the action proposal"
    )


class AgentPlan(BaseModel):
    """
    A bounded execution plan generated by Nemotron 3 Super 120B.
    Limited to a configured maximum number of steps to prevent unbounded loops.
    """
    model_config = ConfigDict(extra="forbid")

    summary: str = Field(description="Summary of the intended objective")
    actions: list[ProposedAction] = Field(
        default_factory=list,
        max_length=5,  # Bounded execution: maximum 5 steps per planning cycle
        description="Ordered sequence of proposed actions"
    )
    requires_user_approval: bool = Field(
        default=True,
        description="Flag indicating if any action in the plan is expected to need human approval"
    )
